export function getUnit(unitId) {
  return UNITS.find((u) => u.id === unitId);
}

export function getPeriod(unitId, periodId) {
  const unit = getUnit(unitId);
  if (!unit) return null;
  const period = unit.periods.find((p) => p.id === periodId);
  if (!period) return null;
  return { unit, period };
}